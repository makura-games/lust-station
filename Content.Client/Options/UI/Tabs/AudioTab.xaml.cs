using Content.Client.Administration.Managers;
using Content.Client.Audio;
using Content.Client._Sunrise.CombatMode;
using Content.Shared._Sunrise.CombatMode;
using Content.Shared._Sunrise.SunriseCCVars;
using Content.Shared.CCVar;
using Robust.Client.Audio;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared;
using Robust.Shared.ContentPack;
using Robust.Shared.GameObjects;

namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class AudioTab : Control
{
    [Dependency] private IAudioManager _audio = default!;
    [Dependency] private IClientAdminManager _admin = default!;
    [Dependency] private IResourceManager _resources = default!;
    [Dependency] private IEntityManager _entityManager = default!;

    public AudioTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var masterVolume = Control.AddOptionPercentSlider(
            CVars.AudioMasterVolume,
            SliderVolumeMaster,
            scale: ContentAudioSystem.MasterVolumeMultiplier);
        masterVolume.ImmediateValueChanged += OnMasterVolumeSliderChanged;

        Control.AddOptionPercentSlider(CVars.MidiVolume, SliderVolumeMidi, scale: ContentAudioSystem.MidiVolumeMultiplier);
        Control.AddOptionPercentSlider(CCVars.AmbientMusicVolume, SliderVolumeAmbientMusic, scale: ContentAudioSystem.AmbientMusicMultiplier);
        Control.AddOptionPercentSlider(CCVars.AmbienceVolume, SliderVolumeAmbience, scale: ContentAudioSystem.AmbienceMultiplier);
        Control.AddOptionPercentSlider(CCVars.LobbyMusicVolume, SliderVolumeLobby, scale: ContentAudioSystem.LobbyMultiplier);
        Control.AddOptionPercentSlider(CCVars.InterfaceVolume, SliderVolumeInterface, scale: ContentAudioSystem.InterfaceMultiplier);

        Control.AddOptionCheckBox(CCVars.LobbyMusicEnabled, LobbyMusicCheckBox);
        Control.AddOptionCheckBox(CCVars.RestartSoundsEnabled, RestartSoundsCheckBox);
        Control.AddOptionCheckBox(CCVars.EventMusicEnabled, EventMusicCheckBox);
        Control.AddOptionCheckBox(CCVars.AdminSoundsEnabled, AdminSoundsCheckBox);
        Control.AddOptionCheckBox(CCVars.BwoinkSoundEnabled, BwoinkSoundCheckBox);

        // Sunrise-Edit: Подключены выбор звуков, громкость и предпрослушивание боевой обратной связи.
        var soundOptions = CombatHitFeedbackSoundCatalog.GetOptions(_resources);
        Control.AddOptionCheckBox(SunriseCCVars.CombatHitFeedbackHitEnabled, HitFeedbackEnabledCheckBox);
        Control.AddOptionDropDown(SunriseCCVars.CombatHitFeedbackHitSound, HitFeedbackSoundDropDown, soundOptions);
        Control.AddOptionCheckBox(SunriseCCVars.CombatHitFeedbackCriticalEnabled, CriticalFeedbackEnabledCheckBox);
        Control.AddOptionDropDown(SunriseCCVars.CombatHitFeedbackCriticalSound, CriticalFeedbackSoundDropDown, soundOptions);
        Control.AddOptionCheckBox(SunriseCCVars.CombatHitFeedbackKillEnabled, KillFeedbackEnabledCheckBox);
        Control.AddOptionDropDown(SunriseCCVars.CombatHitFeedbackKillSound, KillFeedbackSoundDropDown, soundOptions);
        Control.AddOptionPercentSlider(SunriseCCVars.CombatHitFeedbackVolume, HitFeedbackVolumeSlider);

        HitFeedbackPreviewButton.OnPressed += _ => Preview(CombatHitFeedbackType.Hit, HitFeedbackSoundDropDown);
        CriticalFeedbackPreviewButton.OnPressed += _ => Preview(CombatHitFeedbackType.Critical, CriticalFeedbackSoundDropDown);
        KillFeedbackPreviewButton.OnPressed += _ => Preview(CombatHitFeedbackType.Kill, KillFeedbackSoundDropDown);

        Control.Initialize();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _admin.AdminStatusUpdated += UpdateAdminButtonsVisibility;
        UpdateAdminButtonsVisibility();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _admin.AdminStatusUpdated -= UpdateAdminButtonsVisibility;
    }

    private void UpdateAdminButtonsVisibility()
    {
        BwoinkSoundCheckBox.Visible = _admin.IsActive();
    }

    private void Preview(CombatHitFeedbackType type, OptionDropDown dropDown)
    {
        var selectedId = dropDown.Button.SelectedMetadata as string;
        _entityManager.System<CombatHitFeedbackSystem>().PlayPreview(type, selectedId);
    }

    private void OnMasterVolumeSliderChanged(float value)
    {
        _audio.SetMasterGain(value);
    }
}
