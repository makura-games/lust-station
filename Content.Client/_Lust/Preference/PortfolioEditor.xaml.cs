using Content.Shared._Lust.Preferences;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Preferences;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Lust.Preference;

[GenerateTypedNameReferences]
public sealed partial class PortfolioEditor : Control
{
    private sealed record PortfolioField(
        Func<PortfolioProfile, string> Get,
        Action<PortfolioProfile, string> Set);

    private static readonly PortfolioField DistinguishingFeatures =
        new(p => p.DistinguishingFeatures, (p, v) => p.DistinguishingFeatures = v);

    private static readonly PortfolioField Region =
        new(p => p.Region, (p, v) => p.Region = v);

    private static readonly PortfolioField PlanetOrColony =
        new(p => p.PlanetOrColony, (p, v) => p.PlanetOrColony = v);

    private static readonly PortfolioField Address =
        new(p => p.Address, (p, v) => p.Address = v);

    private static readonly PortfolioField Education =
        new(p => p.Education, (p, v) => p.Education = v);

    private static readonly PortfolioField WorkExperience =
        new(p => p.WorkExperience, (p, v) => p.WorkExperience = v);

    private static readonly PortfolioField CloseRelatives =
        new(p => p.CloseRelatives, (p, v) => p.CloseRelatives = v);

    private static readonly PortfolioField EmergencyContact =
        new(p => p.EmergencyContact, (p, v) => p.EmergencyContact = v);

    private static readonly PortfolioField PhysiologicalTraits =
        new(p => p.PhysiologicalTraits, (p, v) => p.PhysiologicalTraits = v);

    private static readonly PortfolioField PsychologicalTraits =
        new(p => p.PsychologicalTraits, (p, v) => p.PsychologicalTraits = v);

    private static readonly PortfolioField ArrestHistory =
        new(p => p.ArrestHistory, (p, v) => p.ArrestHistory = v);

    private static readonly PortfolioField ConvictionHistory =
        new(p => p.ConvictionHistory, (p, v) => p.ConvictionHistory = v);

    private PortfolioProfile _portfolio = new();
    private Func<ProtoId<SpeciesPrototype>>? _getSpecies;

    /// <summary>
    /// Источник текущего вида из родительского редактора — задаётся после создания.
    /// </summary>
    internal Func<ProtoId<SpeciesPrototype>>? SpeciesProvider
    {
        set => _getSpecies = value;
    }

    private ProtoId<SpeciesPrototype> SpeciesId =>
        _getSpecies?.Invoke() ?? HumanoidCharacterProfile.DefaultSpecies;

    /// <summary>
    /// Вызывается при изменении любого поля портфолио.
    /// </summary>
    public event Action<PortfolioProfile>? OnPortfolioChanged;

    /// <summary>
    /// Создаёт вкладку редактора портфолио и подписывает контролы на ввод и генерацию.
    /// </summary>
    public PortfolioEditor()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        MaritalStatusButton.Clear();
        foreach (var status in Enum.GetValues<MaritalStatus>())
        {
            MaritalStatusButton.AddItem(
                Loc.GetString($"lust-humanoid-profile-editor-portfolio-marital-{status.ToString().ToLowerInvariant()}-text"),
                (int) status);
        }

        MaritalStatusButton.OnItemSelected += args =>
        {
            MaritalStatusButton.SelectId(args.Id);
            WriteMaritalStatus((MaritalStatus) args.Id);
        };

        // Однострочные поля (128/32 символа), пишем по OnTextEntered и OnFocusExit.
        SubscribeSingle(Region, RegionEdit);
        SubscribeSingle(PlanetOrColony, PlanetOrColonyEdit);
        SubscribeSingle(Address, AddressEdit);

        // Многострочные поля (512 символов), у TextEdit нет OnTextEntered и OnFocusExit.
        SubscribeMulti(DistinguishingFeatures, DistinguishingFeaturesEdit);
        SubscribeMulti(Education, EducationEdit);
        SubscribeMulti(WorkExperience, WorkExperienceEdit);
        SubscribeMulti(CloseRelatives, CloseRelativesEdit);
        SubscribeMulti(EmergencyContact, EmergencyContactEdit);
        SubscribeMulti(PhysiologicalTraits, PhysiologicalTraitsEdit);
        SubscribeMulti(PsychologicalTraits, PsychologicalTraitsEdit);
        SubscribeMulti(ArrestHistory, ArrestHistoryEdit);
        SubscribeMulti(ConvictionHistory, ConvictionHistoryEdit);

        DistinguishingFeaturesGen.OnPressed += _ => GenerateDistinguishingFeatures();
        RegionGen.OnPressed += _ => GenerateRegion();
        PlanetOrColonyGen.OnPressed += _ => GeneratePlanetOrColony();
        AddressGen.OnPressed += _ => GenerateAddress();
        EducationGen.OnPressed += _ => GenerateEducation();
        WorkExperienceGen.OnPressed += _ => GenerateWorkExperience();
        CloseRelativesGen.OnPressed += _ => GenerateCloseRelatives();
        EmergencyContactGen.OnPressed += _ => GenerateEmergencyContact();
        PhysiologicalTraitsGen.OnPressed += _ => GeneratePhysiologicalTraits();
        PsychologicalTraitsGen.OnPressed += _ => GeneratePsychologicalTraits();
        ArrestHistoryGen.OnPressed += _ => GenerateArrestHistory();
        ConvictionHistoryGen.OnPressed += _ => GenerateConvictionHistory();
    }

    /// <summary>
    /// однострочное поле, пишем по OnTextEntered и OnFocusExit.
    /// </summary>
    private void SubscribeSingle(PortfolioField field, LineEdit edit)
    {
        edit.OnTextEntered += e => WriteField(field, e.Text);
        edit.OnFocusExit += e => WriteField(field, e.Text);
    }

    /// <summary>
    /// Подписка на многострочные поля для их перезаписи при каждом изменение текста
    /// </summary>
    private void SubscribeMulti(PortfolioField field, TextEdit edit)
    {
        edit.OnTextChanged += _ => WriteField(field, Rope.Collapse(edit.TextRope));
    }

    private static void WriteMulti(TextEdit edit, string value)
    {
        if (Rope.Collapse(edit.TextRope) == value)
            return;

        edit.TextRope = new Rope.Leaf(value);
    }

    /// <summary>
    /// Заливает контролы данными портфолио.
    /// </summary>
    public void SetProfile(PortfolioProfile portfolio)
    {
        _portfolio = new PortfolioProfile(portfolio);

        WriteMulti(DistinguishingFeaturesEdit, DistinguishingFeatures.Get(_portfolio));
        RegionEdit.Text = Region.Get(_portfolio);
        PlanetOrColonyEdit.Text = PlanetOrColony.Get(_portfolio);
        AddressEdit.Text = Address.Get(_portfolio);
        WriteMulti(EducationEdit, Education.Get(_portfolio));
        WriteMulti(WorkExperienceEdit, WorkExperience.Get(_portfolio));
        var maritalStatus = _portfolio.MaritalStatusValue;
        MaritalStatusButton.SelectId(
            Enum.IsDefined(maritalStatus) ? (int) maritalStatus : (int) MaritalStatus.Single);
        WriteMulti(CloseRelativesEdit, CloseRelatives.Get(_portfolio));
        WriteMulti(EmergencyContactEdit, EmergencyContact.Get(_portfolio));
        WriteMulti(PhysiologicalTraitsEdit, PhysiologicalTraits.Get(_portfolio));
        WriteMulti(PsychologicalTraitsEdit, PsychologicalTraits.Get(_portfolio));
        WriteMulti(ArrestHistoryEdit, ArrestHistory.Get(_portfolio));
        WriteMulti(ConvictionHistoryEdit, ConvictionHistory.Get(_portfolio));
    }

    private void WriteField(PortfolioField field, string value)
    {
        var next = new PortfolioProfile(_portfolio);
        field.Set(next, value);
        _portfolio = next;
        OnPortfolioChanged?.Invoke(next);
    }

    private void GenerateDistinguishingFeatures()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.DistinguishingFeatures, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(DistinguishingFeatures, value);
        WriteMulti(DistinguishingFeaturesEdit, value);
    }

    private void GenerateRegion()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.Region, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(Region, value);
        RegionEdit.Text = value;
    }

    private void GeneratePlanetOrColony()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.PlanetOrColony, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(PlanetOrColony, value);
        PlanetOrColonyEdit.Text = value;
    }

    private void GenerateAddress()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.Address, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(Address, value);
        AddressEdit.Text = value;
    }

    private void GenerateEducation()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.Education, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(Education, value);
        WriteMulti(EducationEdit, value);
    }

    private void GenerateWorkExperience()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.WorkExperience, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(WorkExperience, value);
        WriteMulti(WorkExperienceEdit, value);
    }

    private void GenerateCloseRelatives()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.CloseRelatives, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(CloseRelatives, value);
        WriteMulti(CloseRelativesEdit, value);
    }

    private void GenerateEmergencyContact()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.EmergencyContact, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(EmergencyContact, value);
        WriteMulti(EmergencyContactEdit, value);
    }

    private void GeneratePhysiologicalTraits()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.PhysiologicalTraits, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(PhysiologicalTraits, value);
        WriteMulti(PhysiologicalTraitsEdit, value);
    }

    private void GeneratePsychologicalTraits()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.PsychologicalTraits, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(PsychologicalTraits, value);
        WriteMulti(PsychologicalTraitsEdit, value);
    }

    private void GenerateArrestHistory()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.ArrestHistory, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(ArrestHistory, value);
        WriteMulti(ArrestHistoryEdit, value);
    }

    private void GenerateConvictionHistory()
    {
        var value = PortfolioGenerator.Generate(PortfolioPoolLust.ConvictionHistory, SpeciesId);
        if (string.IsNullOrEmpty(value))
            return;

        WriteField(ConvictionHistory, value);
        WriteMulti(ConvictionHistoryEdit, value);
    }

    private void WriteMaritalStatus(MaritalStatus status)
    {
        var next = new PortfolioProfile(_portfolio)
        {
            MaritalStatusValue = status,
        };
        _portfolio = next;
        OnPortfolioChanged?.Invoke(next);
    }
}
