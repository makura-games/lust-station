namespace Content.Shared._Lust.Preferences;

/// <summary>
/// Единые лимиты длин для портфолио.
/// Используются клиентом, сервером и БД-моделью, чтобы значения не расходились.
/// </summary>
/// <remarks>
/// Изначальные значения: 512 для многострочных полей портфолио,
/// 128 для коротких
/// При изменении любого лимита в сторону увеличения НЕОБХОДИМА новая миграция,
/// иначе БД отклонит строки длиннее текущей колонки.
/// </remarks>
public static class LustPorftolioLimits
{
    /// <summary>
    /// Многострочные поля портфолио (черты, образование, история и т.д.).
    /// </summary>
    public const int PortfolioText = 512;

    /// <summary>
    /// Короткие поля портфолио (регион, планета, адрес).
    /// </summary>
    public const int PortfolioShortText = 128;

}
